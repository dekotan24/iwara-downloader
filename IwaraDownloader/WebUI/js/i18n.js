let I18N_LANG = 'ja';

function t(key, ...args) {
    let s = (I18N[I18N_LANG] && I18N[I18N_LANG][key]) ?? I18N['ja'][key] ?? key;
    args.forEach((a, i) => { s = s.replaceAll(`{${i}}`, a); });
    return s;
}

// アプリ設定から言語を取得し、静的HTMLへ適用する。app.js の初期化より先に await すること
async function initI18n() {
    try {
        const r = await fetch('/api/config');
        if (r.ok) {
            const c = await r.json();
            if (c.language && I18N[c.language]) I18N_LANG = c.language;
        }
    } catch { /* 取得失敗時は日本語のまま */ }

    document.documentElement.lang = I18N_LANG;
    document.title = t('title');
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
